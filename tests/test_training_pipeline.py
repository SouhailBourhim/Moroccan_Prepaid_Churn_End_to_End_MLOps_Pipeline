def test_load_config_merges_dataset_overlay(tmp_path: Path) -> None:
    base = tmp_path / "base.yaml"
    base.write_text(
        "training:\n  random_state: 1\nxgboost:\n  max_depth: 7\n  gamma: 0.0\n"
    )
    (tmp_path / "moroccan.yaml").write_text("xgboost:\n  gamma: 4.9\n")

    merged = load_config("moroccan", base)
    assert merged["xgboost"] == {"max_depth": 7, "gamma": 4.9}
    assert merged["training"]["random_state"] == 1
    # Another dataset (no overlay file) sees only the base values.
    assert load_config("expresso", base)["xgboost"]["gamma"] == 0.0


