def test_fit_calibration_improves_brier_of_inflated_scores() -> None:
    rng = np.random.default_rng(0)
    p_true = rng.uniform(0, 0.2, 4000)
    y = (rng.random(4000) < p_true).astype(int)
    inflated = np.clip(p_true * 4, 0, 1)   # mimics class-weighted training
    result = fit_calibration(inflated, y, cv_folds=5, random_state=0)

    assert result.method in ("isotonic", "sigmoid")
    assert set(result.brier_by_method) == {"isotonic", "sigmoid"}
    assert len(result.cross_fitted) == len(y)
    raw_brier = float(np.mean((inflated - y) ** 2))
    assert result.brier_by_method[result.method] < raw_brier


def test_calibrated_model_returns_two_column_probabilities() -> None:
    from sklearn.linear_model import LogisticRegression

    rng = np.random.default_rng(1)
    X = rng.normal(size=(300, 3))
    y = (X[:, 0] > 0).astype(int)
    base = LogisticRegression().fit(X, y)
    result = fit_calibration(base.predict_proba(X)[:, 1], y, cv_folds=3, random_state=0)
    model = CalibratedChurnModel(base, result.calibrator, result.method)

    proba = model.predict_proba(X)
    assert proba.shape == (300, 2)
    np.testing.assert_allclose(proba.sum(axis=1), 1.0)
    assert ((proba >= 0) & (proba <= 1)).all()


# ── End to end: featurize → train → evaluate on tiny data ─────────────────────


TINY_CONFIG = """
training: {random_state: 0, test_size: 0.25, cv_folds: 3, early_stopping_rounds: 5}
xgboost: {n_estimators: 30, max_depth: 3, learning_rate: 0.2, subsample: 0.9,
          colsample_bytree: 0.9, min_child_weight: 1, reg_alpha: 0.0, reg_lambda: 1.0,
          gamma: 0.0}
lightgbm: {n_estimators: 30, max_depth: 3, learning_rate: 0.2, num_leaves: 7,
           subsample: 0.9, colsample_bytree: 0.9, min_child_samples: 5,
           reg_alpha: 0.0, reg_lambda: 1.0}
catboost: {iterations: 30, depth: 3, learning_rate: 0.2, l2_leaf_reg: 3.0,
           subsample: 0.9, colsample_bylevel: 0.9, min_data_in_leaf: 5}
logistic_regression: {C: 1.0, max_iter: 2000}
mlflow: {experiment_name: test, tracking_uri: mlruns}
"""


def _write_features(tmp_path: Path) -> None:
    """Write train/holdout parquet the way run_pipeline does: split first, then fit."""
    raw = make_raw_frame(900, seed=3)
    train_raw, holdout_raw = raw.iloc[:675].reset_index(drop=True), raw.iloc[675:]
    paths = dataset_paths("expresso", tmp_path)
    paths.ensure_dirs()

    pipe = FeaturePipeline(top_pack_min_freq=10, target_enc_cv=3, random_state=0)
    train_fe = pipe.fit_transform(train_raw.drop(columns=["CHURN"]), train_raw["CHURN"])
    cols = get_model_features(train_fe)
    train_out = train_fe[cols].copy()
    train_out["CHURN"] = train_raw["CHURN"].to_numpy()
    train_out.to_parquet(paths.train_features, index=False)

    hold_fe = pipe.transform(holdout_raw.drop(columns=["CHURN"]))
    hold_out = hold_fe[cols].copy()
    hold_out.insert(0, "user_id", holdout_raw["user_id"].to_numpy())
    hold_out["CHURN"] = holdout_raw["CHURN"].to_numpy()
    hold_out.to_parquet(paths.holdout_features, index=False)
    joblib.dump(pipe, paths.feature_pipeline)


def test_train_then_evaluate_end_to_end(
    tmp_path: Path, monkeypatch: pytest.MonkeyPatch
) -> None:
    from src.models import evaluate_run, train

    cfg_path = tmp_path / "base.yaml"
    cfg_path.write_text(TINY_CONFIG)
    _write_features(tmp_path)

    def tmp_paths(ds: str) -> config_mod.DatasetPaths:
        return dataset_paths(ds, tmp_path)

    monkeypatch.setattr(train, "dataset_paths", tmp_paths)
    monkeypatch.setattr(evaluate_run, "dataset_paths", tmp_paths)

    best = train.train(dataset="expresso", use_mlflow=False, config_path=cfg_path)
    paths = tmp_paths("expresso")

    artifact = joblib.load(paths.model)
    assert isinstance(artifact["model"], CalibratedChurnModel)
    assert artifact["model_name"] == best.name
    assert set(artifact["thresholds"]) == {"youden", "f1"}
    assert 0.0 < artifact["default_threshold"] < 1.0

    manifest = json.loads(paths.training_manifest.read_text())
    assert manifest["best_model"] == best.name
    assert manifest["calibration"]["method"] in ("isotonic", "sigmoid")
    assert {r["name"] for r in manifest["all_results"]} == {
        "logistic_regression", "xgboost", "lightgbm", "catboost"
    }

    metrics = evaluate_run.run(dataset="expresso", use_mlflow=False, config_path=cfg_path)
    holdout = pd.read_parquet(paths.holdout_features)
    assert metrics["holdout_size"] == len(holdout)
    assert 0.5 < metrics["roc_auc"] <= 1.0
    # Thresholds are applied as frozen in training, never re-tuned on the holdout.
    assert metrics["threshold_f1"] == pytest.approx(artifact["thresholds"]["f1"])
    assert "uncalibrated_brier" in metrics
    assert json.loads(paths.eval_metrics.read_text())["roc_auc"] == pytest.approx(
        metrics["roc_auc"]
    )
